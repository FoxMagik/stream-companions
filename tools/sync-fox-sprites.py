#!/usr/bin/env python3
"""Push a new fox sprite sheet into every copy of the companion, so they never drift apart.

Usage (from the repo root):
    python3 tools/sync-fox-sprites.py path/to/fox_web_atlas.png path/to/fox_web_atlas.json [--foxden ../foxden]

Updates:
  - assets/fox-sprites.png                       (canonical sheet)
  - stream-fox.html, chromebook-pet.html          (embedded FOX_SHEET block)
  - chrome-extension/content.js + chromebook-extension.zip
  - omarchy-plugin/fox.companion/fox-sprites.png + spriteAnims table in Service.qml
  - foxden/public/pixel-fox.js (copy of content.js) when --foxden is given

The atlas + JSON come from fox3d/scripts/web_atlas.py. Side rows in the sheet face LEFT.
After syncing: bump CACHE_NAME in sw.js if the HTML changed, and restart the Omarchy shell
(Super+Shift+Z) so the desktop pet reloads (its QML is cached until a full restart).
"""
import argparse, base64, json, pathlib, re, shutil, sys, zipfile

ap = argparse.ArgumentParser()
ap.add_argument("atlas"); ap.add_argument("meta"); ap.add_argument("--foxden")
args = ap.parse_args()
repo = pathlib.Path(__file__).resolve().parent.parent
png = pathlib.Path(args.atlas).read_bytes()
meta = json.loads(pathlib.Path(args.meta).read_text())
cw, ch, anims, props = meta["cw"], meta["ch"], meta["anims"], meta.get("props", {})

def js_block(ind):
    b64 = base64.b64encode(png).decode()
    lines = [
        "// === Fox sprite sheet (pixel art, generated by fox3d/scripts/web_atlas.py) ===",
        f"const FOX_SHEET = {{ cw: {cw}, ch: {ch}, anims: {json.dumps(anims, separators=(',', ':'))}, props: {json.dumps(props, separators=(',', ':'))} }};",
        "const FOX_SHEET_IMG = new Image();",
        f'FOX_SHEET_IMG.src = "data:image/png;base64,{b64}";',
        "// Side rows face LEFT in the sheet; mirror them when facing right (or use a pre-mirrored rowR). Front rows as-is.",
        "function drawFoxSprite(ctx, anim, frameIdx, faceRight, scale) {",
        "  const a = FOX_SHEET.anims[anim] || FOX_SHEET.anims.idle;",
        "  const W = FOX_SHEET.cw * scale, H = FOX_SHEET.ch * scale;",
        "  ctx.clearRect(0, 0, ctx.canvas.width, ctx.canvas.height);",
        "  if (!FOX_SHEET_IMG.complete) return;",
        "  const f = ((frameIdx % a.frames) + a.frames) % a.frames;",
        "  const useR = a.side && faceRight && a.rowR !== undefined;",
        "  ctx.save();",
        "  ctx.imageSmoothingEnabled = scale < 1;   // smooth only when shrinking",
        "  if (a.side && faceRight && !useR) { ctx.translate(W, 0); ctx.scale(-1, 1); }",
        "  ctx.drawImage(FOX_SHEET_IMG, f * FOX_SHEET.cw, (useR ? a.rowR : a.row) * FOX_SHEET.ch, FOX_SHEET.cw, FOX_SHEET.ch, 0, 0, W, H);",
        "  ctx.restore();",
        "}",
        "// Props (butterfly / ball) at the fox's pixel size: centred; the ball sits on the canvas bottom.",
        "function drawPropSprite(ctx, kind, frameIdx, scale) {",
        "  const frames = FOX_SHEET.props[kind];",
        "  ctx.clearRect(0, 0, ctx.canvas.width, ctx.canvas.height);",
        "  if (!frames || !FOX_SHEET_IMG.complete) return;",
        "  const [sx, sy, sw, sh] = frames[((Math.floor(frameIdx) % frames.length) + frames.length) % frames.length];",
        "  const w = Math.round(sw * scale), h = Math.round(sh * scale);",
        "  const dx = Math.round((ctx.canvas.width - w) / 2);",
        "  const dy = kind === \"ball\" ? ctx.canvas.height - h : Math.round((ctx.canvas.height - h) / 2);",
        "  ctx.save();",
        "  ctx.imageSmoothingEnabled = scale < 1;",
        "  ctx.drawImage(FOX_SHEET_IMG, sx, sy, sw, sh, dx, dy, w, h);",
        "  ctx.restore();",
        "}",
        "// === end fox sprite sheet ===",
    ]
    return "".join(ind + l + "\n" for l in lines)

BLOCK = re.compile(r"^( *)// === Fox sprite sheet .*?^\1// === end fox sprite sheet ===\n", re.S | re.M)
OLD_BLOCK = re.compile(r"^( *)// === Fox sprite sheet .*?^\1function drawFoxSprite\(.*?^\1\}\n", re.S | re.M)   # before the end marker existed
changed = []
for rel in ["stream-fox.html", "chromebook-pet.html", "chrome-extension/content.js"]:
    p = repo / rel; text = p.read_text()
    m = list(BLOCK.finditer(text)) or list(OLD_BLOCK.finditer(text))
    if len(m) != 1: sys.exit(f"{rel}: expected exactly one FOX_SHEET block, found {len(m)}")
    new = text[:m[0].start()] + js_block(m[0].group(1)) + text[m[0].end():]
    if new != text: p.write_text(new); changed.append(rel)

(repo / "assets/fox-sprites.png").write_bytes(png)
plugin = repo / "omarchy-plugin/fox.companion"
(plugin / "fox-sprites.png").write_bytes(png)
qml = plugin / "Service.qml"; text = qml.read_text()
pat = re.compile(r"^(  readonly property var spriteAnims: )\(.*\)$", re.M)
if len(pat.findall(text)) != 1: sys.exit("Service.qml: spriteAnims line not found exactly once")
new = pat.sub(lambda m_: m_.group(1) + "(" + json.dumps(anims, separators=(", ", ": ")) + ")", text)
ppat = re.compile(r"^(  readonly property var spriteProps: )\(.*\)$", re.M)
if len(ppat.findall(new)) != 1: sys.exit("Service.qml: spriteProps line not found exactly once")
new = ppat.sub(lambda m_: m_.group(1) + "(" + json.dumps(props, separators=(", ", ": ")) + ")", new)
new = re.sub(r"readonly property int cellW: \d+", f"readonly property int cellW: {cw}", new)
new = re.sub(r"readonly property int cellH: \d+", f"readonly property int cellH: {ch}", new)
if new != text: qml.write_text(new); changed.append(str(qml.relative_to(repo)))

zpath = repo / "chromebook-extension.zip"
want = {n: (repo / "chrome-extension" / n).read_bytes() for n in ["manifest.json", "content.js"]}
try:
    with zipfile.ZipFile(zpath) as z: have = {n: z.read(n) for n in z.namelist()}
except (FileNotFoundError, zipfile.BadZipFile):
    have = {}
if have != want:   # only rewrite when the contents differ (avoids noisy binary diffs)
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        for n, data in want.items(): z.writestr(n, data)
    changed.append("chromebook-extension.zip")
if args.foxden:
    dst = pathlib.Path(args.foxden) / "public/pixel-fox.js"
    if not dst.exists() or dst.read_bytes() != want["content.js"]:
        dst.write_bytes(want["content.js"]); changed.append(str(dst))

print("synced:", ", ".join(changed) if changed else "(embedded copies already up to date)")
print("next: bump CACHE_NAME in sw.js if HTML changed; Super+Shift+Z to reload the desktop pet")
